using System;
using System.Collections.Generic;
using System.Linq;
using Jerrycurl.CodeAnalysis.Lexing;
using Jerrycurl.CodeAnalysis.Projection;
using Jerrycurl.CodeAnalysis.Razor.Lexing.CSharp;
using Jerrycurl.CodeAnalysis.Razor.Parsing;
using Jerrycurl.CodeAnalysis.Razor.Parsing.Directives;
using Jerrycurl.CodeAnalysis.Razor.Parsing.Fragments;

namespace Jerrycurl.CodeAnalysis.Razor.Generation;

public class RazorGenerator
{
    public RazorGeneratorOptions Options { get; }

    public RazorGenerator(RazorGeneratorOptions options)
    {
        this.Options = options ?? throw new ArgumentNullException(nameof(options));
    }

    public ProjectionResult Generate(RazorPageData pageData)
    {
        ISource template = new StringSource(this.Options.TemplateCode);

        Projector projector = new Projector(template);
        IList<RazorFragment> mergedContent = [.. this.MergeContent(pageData.Content)];

        foreach (RazorFragment fragment in mergedContent)
        {
            switch (fragment)
            {
                case SqlFragment sql:
                    projector.Open("execute")
                        .WriteLine($"WriteLiteral({CSharp.Literal(sql.Text)});");
                    break;
                case CodeFragment code when code.CodeType == CSharpType.Statement:
                    projector.Open("execute").WritePragma(code);
                    break;
                case CodeFragment code when code.CodeType == CSharpType.Expression:
                    projector.Open("execute")
                        .Write("Write(")
                        .WritePragma(code)
                        .WriteLine(");");
                    break;
            }
        }

        SqlFragment firstSql = mergedContent.OfType<SqlFragment>().FirstOrDefault(sql => sql.Text.Length > 0);

        projector.Open("throw")
            .Write($"#line {firstSql?.Span?.Line ?? 1} {CSharp.FileName(pageData.SourceName)}")
            .WriteLine()
            .Write("throw ex;")
            .WriteLine()
            .WriteLine("#line default")
            .WriteLine("#line hidden");

        if (pageData.SourceChecksum != null)
        {
            projector.Open("pragmachecksum")
                .Write($"#pragma checksum {CSharp.FileName(pageData.SourceName)} \"{{ff1816ec-aa5e-4d10-87f7-6f4963833460}}\" \"{pageData.SourceChecksum}\"");
        }

        projector.Open("autogenerated")
            .Write("// <auto-generated/>");

        string className = pageData.Class?.Text ?? this.Options.Class?.Text ?? "MyRazorPage";

        projector.Open("visibility").Write(this.GetVisibility(pageData));

        this.WriteEntryPoints(projector, pageData, className.Trim());

        if (pageData.Model?.Text != null)
            projector.Open("model").WritePragma(pageData.Model);
        else if (pageData.Input != null)
            projector.Open("model").Write($"{className}.Input");
        else
            projector.Open("model").Write("dynamic");

        if (pageData.Result?.Text != null)
            projector.Open("result").WritePragma(pageData.Result);
        else if (pageData.Output != null)
            projector.Open("result").Write($"{className}.Output");
        else
            projector.Open("result").Write("object");

        if (pageData.Class?.Text != null)
            projector.Open("class").WritePragma(pageData.Class);
        else if (this.Options.Class?.Text != null)
            projector.Open("class").Write(this.Options.Class.Text);
        else
            projector.Open("class").Write("MyRazorPage");

        if (!string.IsNullOrWhiteSpace(pageData.Template?.Text))
        {
            string templateText = pageData.Template.Text.Trim();

            if (templateText.StartsWith("\"") || templateText.StartsWith("@\"") || templateText.StartsWith("$\""))
            {
                pageData.Diagnostics.Add(RazorDiagnostics.Error(RazorDiagnostics.InvalidSyntax, "Invalid directive syntax", $"@template takes a page type, not a string: use '@template {templateText.Trim('@', '$', '"').Replace(".cssql", "").Replace('/', '.')}'.", pageData.Template, pageData.SourceName));
            }
            else
            {
                projector.Open("template")
                    .Write("[global::Jerrycurl.Mvc.Metadata.Annotations.Template(typeof(")
                    .WritePragma(pageData.Template)
                    .Write("))]");
            }
        }

        if (pageData.Input?.Text != null)
            WriteType("inputtype", "Input", pageData.Input);

        if (pageData.Output?.Text != null)
            WriteType("outputtype", "Output", pageData.Output);

        foreach (InjectDirective inject in pageData.Injections ?? [])
        {
            if (string.IsNullOrWhiteSpace(inject.Type.Text) || string.IsNullOrWhiteSpace(inject.Variable?.Text))
                projector.WriteWarning(inject.Type, "Injection ignored. Please specify both type and variable name.");
            else
            {
                projector.Open("injectiondefs")
                    .WriteLine("[global::Jerrycurl.Mvc.Metadata.Annotations.Inject]")
                    .Write("public ")
                    .WritePragma(inject.Type)
                    .WritePragma(inject.Variable)
                    .WriteLine(" { get; set; }");
            }
        }

        foreach (InjectDirective project in pageData.Projections ?? [])
        {
            projector.Open("injectiondefs");

            if (string.IsNullOrWhiteSpace(project.Type?.Text) || string.IsNullOrWhiteSpace(project.Variable?.Text))
                projector.WriteWarning(project.Type, "Projection ignored. Please specify both type and variable name.");
            else
            {
                projector.WriteLine("[global::Jerrycurl.Mvc.Metadata.Annotations.Inject]")
                    .Write("public global::Jerrycurl.Mvc.Projections.IProjection<")
                    .WritePragma(project.Type)
                    .Write("> ")
                    .WritePragma(project.Variable)
                    .WriteLine(" { get; set; }");
            }
        }

        foreach (RazorFragment import in this.Options.Imports ?? [])
        {
            projector.Open("globalimports")
                .Write("using ")
                .WritePragma(import, terminate: true)
                .WriteLine();
        }

        foreach (RazorFragment import in pageData.Imports ?? [])
        {
            projector.Open("localimports")
                .Write("using ")
                .WritePragma(import, terminate: true)
                .WriteLine();
        }

        if (!string.IsNullOrWhiteSpace(pageData.Namespace?.Text))
        {
            projector.Open("beginnamespace")
                .Write($"namespace ")
                .WritePragma(pageData.Namespace)
                .WriteLine(" {");

            projector.Open("endnamespace")
                .Write("}");
        }
        else if (!string.IsNullOrWhiteSpace(this.Options.Namespace?.Text))
        {
            projector.Open("beginnamespace")
                .Write($"namespace ")
                .Write(this.Options.Namespace.Text)
                .WriteLine(" {");

            projector.Open("endnamespace")
                .Write("}");
        }

        return projector.Generate();

        void WriteType(string target, string typeName, RazorFragment fragment)
        {
            string[] properties = [
                ..ArgumentSplitter.SplitArguments(fragment.Text).Select(arg =>
                {
                    (string declaration, string defaultValue) = ArgumentSplitter.SplitDefault(arg);

                    if (defaultValue != null)
                        return $"public {declaration} {{ get; set; }} = {defaultValue};";

                    return $"public {declaration} {{ get; set; }}";
                })
            ];

            projector.Open(target)
                .WriteLine($"public class {typeName}")
                .WriteLine("{")
                .WriteLine(string.Join("\n", properties))
                .WriteLine("}");
        }
    }

    private string GetVisibility(RazorPageData pageData)
    {
        if (pageData.Visibility != null && RazorParser.IsValidVisibility(pageData.Visibility.Text))
            return pageData.Visibility.Text.Trim();
        else if (RazorParser.IsValidVisibility(this.Options.DefaultVisibility))
            return this.Options.DefaultVisibility.Trim();

        return "internal";
    }

    private static readonly string[] QueryMethods = ["Query", "QueryAsync", "Aggregate", "AggregateAsync", "Enumerate", "EnumerateAsync"];
    private static readonly string[] CommandMethods = ["Execute", "ExecuteAsync"];

    private void WriteEntryPoints(Projector projector, RazorPageData pageData, string className)
    {
        const string Configure = "global::System.Action<global::Jerrycurl.Mvc.SqlOptions> configure = null";
        const string Engine = "global::Jerrycurl.Mvc.IProcEngine engine = null";
        const string Token = "global::System.Threading.CancellationToken cancellationToken = default";

        if (pageData.Query != null && pageData.Command != null)
        {
            pageData.Diagnostics.Add(RazorDiagnostics.Error(RazorDiagnostics.BothKinds, "Page is both @query and @command", "A page can't be both @query and @command.", pageData.Command, pageData.SourceName));

            return;
        }

        if (pageData.Kind == RazorPageKind.Partial)
        {
            pageData.Diagnostics.Add(RazorDiagnostics.Create(RazorDiagnostics.PartialPage, "Partial page", $"Page '{className}' has no @query or @command and is only usable as a partial (@template, Subquery, Subcommand).", RazorDiagnosticSeverity.Info, null, pageData.SourceName));

            return;
        }

        string[] methods = pageData.Kind == RazorPageKind.Query ? QueryMethods : CommandMethods;

        if (methods.Contains(className))
        {
            string directive = pageData.Kind == RazorPageKind.Query ? "@query" : "@command";

            pageData.Diagnostics.Add(RazorDiagnostics.Error(RazorDiagnostics.NameClash, "Page name clashes with its entry points", $"A {directive} page can't be named '{className}', because it would clash with its generated '{className}' method. Rename the file or use @class.", pageData.Query ?? pageData.Command, pageData.SourceName));

            return;
        }

        string model = pageData.Model?.Text?.Trim() is { Length: > 0 } m ? m : pageData.Input != null ? "Input" : "object";
        string type = $"typeof({className})";
        string args = $"{model} model = default, {Configure}, {Engine}";
        string asyncArgs = $"{args}, {Token}";

        projector.Open("entrypoints");

        if (pageData.Kind == RazorPageKind.Command)
        {
            if (pageData.Output != null || pageData.Result != null)
                pageData.Diagnostics.Add(RazorDiagnostics.Error(RazorDiagnostics.OutputOnCommand, "@output on a @command", "A @command can't declare @output or @result. Commands write their results back into the model.", pageData.Output ?? pageData.Result, pageData.SourceName));

            projector
                .WriteLine($"public static void Execute({args})")
                .WriteLine($"    => ExecuteCore({type}, model, configure, engine);")
                .WriteLine($"public static global::System.Threading.Tasks.Task ExecuteAsync({asyncArgs})")
                .WriteLine($"    => ExecuteCoreAsync({type}, model, configure, engine, cancellationToken);");

            return;
        }

        string result = pageData.Result?.Text?.Trim() is { Length: > 0 } r ? r : pageData.Output != null ? "Output" : "object";

        foreach (string item in new[] { result, "T" })
        {
            string generic = item == "T" ? "<T>" : "";
            string list = $"global::System.Collections.Generic.IList<{item}>";

            projector
                .WriteLine($"public static {list} Query{generic}({args})")
                .WriteLine($"    => QueryCore<{item}>({type}, model, configure, engine);")
                .WriteLine($"public static global::System.Threading.Tasks.Task<{list}> QueryAsync{generic}({asyncArgs})")
                .WriteLine($"    => QueryCoreAsync<{item}>({type}, model, configure, engine, cancellationToken);")
                .WriteLine($"public static {item} Aggregate{generic}({args})")
                .WriteLine($"    => AggregateCore<{item}>({type}, model, configure, engine);")
                .WriteLine($"public static global::System.Threading.Tasks.Task<{item}> AggregateAsync{generic}({asyncArgs})")
                .WriteLine($"    => AggregateCoreAsync<{item}>({type}, model, configure, engine, cancellationToken);")
                .WriteLine($"public static global::System.Collections.Generic.IEnumerable<{item}> Enumerate{generic}({args})")
                .WriteLine($"    => EnumerateCore<{item}>({type}, model, configure, engine);")
                .WriteLine($"public static global::System.Collections.Generic.IAsyncEnumerable<{item}> EnumerateAsync{generic}({asyncArgs})")
                .WriteLine($"    => EnumerateCoreAsync<{item}>({type}, model, configure, engine, cancellationToken);");
        }
    }

    private IEnumerable<RazorFragment> MergeContent(IEnumerable<RazorFragment> fragments)
    {
        List<SqlFragment> sqlBatch = [];

        fragments = fragments.SkipWhile(f => f is SqlFragment sql && string.IsNullOrWhiteSpace(sql.Text));

        if (fragments.FirstOrDefault() is SqlFragment sql2)
        {
            SqlFragment trimSql = new SqlFragment()
            {
                SourceName = sql2.SourceName,
                Span = sql2.Span,
                Text = sql2.Text.TrimStart()
            };

            sqlBatch.Add(trimSql);

            fragments = fragments.Skip(1);
        }

        foreach (RazorFragment fragment in fragments)
        {
            if (fragment is SqlFragment sql3)
            {
                sqlBatch.Add(sql3);

                continue;
            }
            else if (sqlBatch.Count > 0)
            {
                yield return this.MergeSql(sqlBatch);

                sqlBatch.Clear();
            }

            yield return fragment;
        }

        if (sqlBatch.Count > 0)
            yield return this.MergeSql(sqlBatch);
    }

    private SqlFragment MergeSql(IEnumerable<SqlFragment> sqlBatch)
    {
        return new SqlFragment()
        {
            Text = string.Join("", sqlBatch.Select(f => f.Text)),
        };
    }
}
